import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/ownership-queue.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports });
const property = { id: 'property', status: 'pending', ownership_verified: false, ownership_review_status: 'unreviewed', deleted_at: null };
const pending = { id: 'doc', property_id: 'property', document_type: 'ownership', status: 'pending', created_at: '2026-11-11T10:00:00Z', properties: property };
assert.equal(exports.isPendingOwnershipReview(pending), true);
const published = { ...pending, properties: { ...property, status: 'active', ownership_verified: true, ownership_review_status: 'approved' } };
assert.equal(exports.isPendingOwnershipReview(published), false);
assert.equal(exports.pendingOwnershipQueue([published]).length, 0);
assert.equal(exports.isPendingOwnershipReview({ ...pending, status: 'approved' }), false);
assert.equal(exports.isPendingOwnershipReview({ ...pending, status: 'rejected' }), false);
assert.equal(exports.isPendingOwnershipReview({ ...pending, properties: { ...property, ownership_review_status: 'rejected' } }), false);
assert.equal(exports.isPendingOwnershipReview({ ...pending, properties: { ...property, deleted_at: '2026-11-11' } }), false);
assert.equal(exports.isPendingOwnershipReview({ ...pending, property_id: 'other' }), false);
assert.equal(exports.isPendingOwnershipReview({ ...pending, properties: [property] }), true);
const newest = { ...pending, id: 'resubmitted', created_at: '2026-11-11T12:00:00Z' };
assert.equal(exports.pendingOwnershipQueue([pending, newest]).length, 1);
assert.equal(exports.pendingOwnershipQueue([pending, newest])[0].id, 'resubmitted');
const approved = { ...published, status: 'approved' };
assert.equal(exports.ownershipDecisionConfirmed(approved, true), true);
assert.equal(exports.ownershipDecisionConfirmed({ ...approved, properties: { ...approved.properties, status: 'pending' } }, true), true);
assert.equal(exports.ownershipDecisionConfirmed(pending, true), false);
const rejected = { ...pending, status: 'rejected', properties: { ...property, status: 'rejected', ownership_review_status: 'rejected' } };
assert.equal(exports.ownershipDecisionConfirmed(rejected, false), true);
assert.equal(exports.pendingOwnershipQueue([rejected, published]).length, 0);
assert.equal(exports.pendingOwnershipQueue([rejected, newest, published]).length, 1);
console.log('Ownership queue checks passed: published/decided/deleted exclusions, newest pending property bundle, legitimate resubmission and saved-decision verification.');
