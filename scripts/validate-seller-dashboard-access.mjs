import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import ts from 'typescript';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const require = createRequire(import.meta.url);
const modules = {};
function load(path) {
  const exports = {};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText, { exports, require: name => modules[name] || require(name) });
  return exports;
}
const policy = load('src/lib/seller-dashboard-access.ts');
modules['@/lib/seller-dashboard-access'] = policy;
modules['next/link'] = { default: ({ children, prefetch, ...props }) => React.createElement('a', props, children) };
const Status = load('src/components/SellerDashboardAccess.tsx').default;
const ready = { role: 'seller', sellerStatus: 'active', kycStatus: 'approved', ownerDeclared: true };
assert.equal(policy.sellerDashboardAccess(ready).allowed, true);
assert.equal(policy.sellerDashboardAccess({ role: 'admin' }).allowed, true);
assert.equal(policy.sellerDashboardAccess({ ...ready, ownerDeclared: false }).reason, 'declaration');
for (const kycStatus of ['pending', 'rejected', 'not_submitted']) assert.equal(policy.sellerDashboardAccess({ ...ready, kycStatus }).reason, 'identity');
for (const sellerStatus of ['basic', 'pending_seller', 'suspended', null]) assert.equal(policy.sellerDashboardAccess({ ...ready, sellerStatus }).reason, 'activation');
assert.equal(policy.sellerDashboardAccess({ ...ready, role: 'buyer' }).allowed, false);
const render = (profile, documents = {}) => renderToStaticMarkup(React.createElement(Status, { profile, documents, onRefresh() {} }));
const screenshot = render({ ...ready, sellerStatus: 'basic' }, { aadhar: { document_url: 'private-id', status: 'approved' } });
assert.ok(screenshot.includes('Upload a selfie'));
assert.ok(screenshot.includes('all three are mandatory'));
assert.ok(screenshot.includes('Completing only one or two is not enough'));
assert.ok(screenshot.includes('One government ID:'));
assert.ok(screenshot.includes('A matching selfie:'));
assert.ok(screenshot.includes('The owner-only declaration:'));
assert.ok(screenshot.includes('Seller access is not active yet'));
assert.ok(!screenshot.includes('Open seller dashboard'));
assert.ok(!screenshot.includes('You can now list properties'));
assert.ok(render(ready).includes('Open seller dashboard'));
const pending = render({ ...ready, kycStatus: 'pending' }, { aadhar: { document_url: 'private-id', status: 'approved' }, selfie: { document_url: 'private-selfie', status: 'pending' } });
assert.ok(pending.includes('Your selfie needs admin approval'));
assert.ok(!pending.includes('Open seller dashboard'));
const restriction = render({ ...ready, sellerStatus: 'suspended' }, { aadhar: { document_url: 'private-id', status: 'approved' }, selfie: { document_url: 'private-selfie', status: 'approved' } });
assert.ok(restriction.includes('Saving the declaration again does not override restricted access'));
let viewer = null;
modules['next/navigation'] = { redirect: href => { throw new Error(`redirect:${href}`); } };
modules['@/lib/auth'] = { getCurrentUser: async () => viewer };
const Layout = load('src/app/(dashboard)/layout.tsx').default;
await assert.rejects(Layout({ children: 'dashboard' }), /redirect:\/login/);
viewer = { ...ready, sellerStatus: 'basic' };
await assert.rejects(Layout({ children: 'dashboard' }), /access=activation/);
viewer = { ...ready, kycStatus: 'pending' };
await assert.rejects(Layout({ children: 'dashboard' }), /access=identity/);
viewer = ready;
assert.ok(renderToStaticMarkup(await Layout({ children: 'dashboard' })).includes('dashboard'));
console.log('Seller dashboard access checks passed: ready seller/admin access, declaration/identity/activation redirects, missing selfie guidance, pending review and restricted access.');
